import { test, expect } from '@playwright/test'
import path from 'node:path'

test('1920×1080 delivery screenshots and alignment', async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('/')
  await page.evaluate(() => document.fonts.ready)
  const screenshot = (name: string) => page.screenshot({ path: path.resolve('..', 'screenshots', name), type: 'png', animations: 'disabled' })
  await expect(page.locator('.tutorial-card')).toBeInViewport()
  await expect(page.locator('.pagination')).toHaveCount(0)
  await expect(page.locator('.steps')).toHaveAttribute('aria-label', '译制流程')
  const steps = await page.locator('.step h3').evaluateAll(nodes => nodes.map(n => n.getBoundingClientRect().top))
  expect(new Set(steps).size).toBe(1)
  await screenshot('02-improved-1920x1080.png')
  await page.getByRole('button', { name: '原版页面', exact: true }).click()
  await expect(page.locator('.reference-table-head')).toBeVisible()
  await screenshot('01-original-1920x1080.png')
  await page.getByRole('button', { name: '优化页面' }).click()
  await page.getByRole('button', { name: '创建原剧', exact: true }).click()
  await expect(page.getByLabel('剧名')).toBeFocused()
  await screenshot('03-create-modal-1920x1080.png')
  await page.getByLabel('剧名').fill('第一部原剧 · 本地演示')
  await page.getByLabel('选择本地视频', { exact: true }).setInputFiles({ name: 'original-demo.mp4', mimeType: 'video/mp4', buffer: Buffer.alloc(1024 * 1024) })
  await page.getByRole('button', { name: '确认创建' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(page.locator('.pagination')).toBeVisible()
  await page.getByRole('button', { name: '关闭提示' }).click()
  await screenshot('04-task-list-1920x1080.png')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(1920)
})
