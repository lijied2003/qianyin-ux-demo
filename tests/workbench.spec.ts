import { test, expect } from '@playwright/test'

test('empty state, validation, creation, persistence, search and reset', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '从你的第一部原剧开始' })).toBeVisible()
  await expect(page.locator('thead')).toHaveCount(0)
  await expect(page.locator('.pagination')).toHaveCount(0)
  await expect(page.locator('.account-text')).toContainText('体验用户')
  await expect(page.locator('.flow-connector')).toHaveCount(2)
  await page.getByRole('button', { name: '原版页面', exact: true }).click()
  await expect(page.locator('.reference-table-head')).toBeVisible()
  await expect(page.locator('.pagination')).toBeVisible()
  await expect(page.locator('.account-text')).toContainText('体验用户')
  await expect(page.locator('.original-tutorial img')).toBeVisible()
  await page.getByRole('button', { name: '展开原剧管理教学' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '优化页面', exact: false }).click()
  await page.getByRole('button', { name: '创建原剧', exact: true }).click()
  await page.getByRole('button', { name: '确认创建' }).click()
  await expect(page.getByRole('alert')).toHaveText('请输入剧名。')
  await page.getByLabel('剧名').fill('我的短剧')
  await page.getByRole('button', { name: '确认创建' }).click()
  await expect(page.getByRole('alert')).toHaveText('请先选择本地视频。')
  await page.getByLabel('选择本地视频', { exact: true }).setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('test') })
  await expect(page.getByRole('alert')).toContainText('MP4')
  await page.getByLabel('选择本地视频', { exact: true }).setInputFiles({ name: 'empty.mp4', mimeType: 'video/mp4', buffer: Buffer.alloc(0) })
  await expect(page.getByRole('alert')).toContainText('为空')
  await page.getByLabel('选择本地视频', { exact: true }).setInputFiles({ name: 'demo.mp4', mimeType: 'video/mp4', buffer: Buffer.from('local metadata test fixture') })
  await page.getByRole('button', { name: '确认创建' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('tbody')).toContainText('我的短剧')
  await expect(page.locator('.pagination')).toBeVisible()
  await expect(page.locator('tbody')).toContainText('待译制')
  await page.getByRole('button', { name: '查看原剧' }).click()
  await expect(page.locator('video')).toHaveCount(1)
  await page.keyboard.press('Escape')
  await page.reload()
  await expect(page.locator('tbody')).toContainText('我的短剧')
  await page.getByRole('button', { name: '查看原剧' }).click()
  await expect(page.getByText('任务信息已保留，重新选择原视频即可预览')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByLabel('搜索剧名').fill('不存在')
  await expect(page.getByText('未找到“')).toBeVisible()
  await page.getByRole('button', { name: '清除搜索' }).click()
  await page.getByRole('button', { name: '译制管理', exact: true }).click()
  await expect(page.getByRole('heading', { name: '还没有译制任务' })).toBeVisible()
  await expect(page.locator('.pagination')).toHaveCount(0)
  await page.getByRole('button', { name: '清空示例数据' }).click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('qianyin-demo-tasks-v1')!).length)).toBe(1)
  await page.getByRole('button', { name: '清空示例数据' }).click()
  await page.getByRole('button', { name: '确认清空' }).click()
  await expect(page.getByRole('heading', { name: '从你的第一部原剧开始' })).toBeVisible()
  await page.reload()
  await expect(page.locator('thead')).toHaveCount(0)
})

test('tutorial, keyboard focus, narrow screen and storage failures', async ({ page }) => {
  await page.goto('/')
  await page.locator('.tutorial-card').click()
  await expect(page.getByRole('dialog')).toContainText('图文教程')
  await page.getByRole('button', { name: '我知道了，创建原剧' }).click()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: '关闭窗口' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: '确认创建' })).toBeFocused()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '创建原剧', exact: true }).click()
  await page.getByLabel('剧名').fill('存储测试')
  await page.getByLabel('选择本地视频', { exact: true }).setInputFiles({ name:'demo.mp4', mimeType:'video/mp4', buffer:Buffer.from('fixture') })
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('quota') } })
  await page.getByRole('button', { name:'确认创建' }).click()
  await expect(page.getByRole('alert')).toContainText('无法保存')
  await expect(page.getByRole('dialog')).toBeVisible()
})

test('malformed local data recovers safely', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('qianyin-demo-tasks-v1','{"unexpected":true}'))
  await page.reload()
  await expect(page.getByRole('heading', { name: '从你的第一部原剧开始' })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('本地数据无法读取')
})
